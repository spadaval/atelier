// Copies what the extension borrows from a T3 Code checkout: its Tailwind theme mapping and the
// components named below, with `~/lib/utils` pointed at ours. Run again after a T3 update.
//   T3=<t3code checkout> node sync-t3.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
const t3 = path.join(process.env.T3 ?? path.join(process.env.HOME, 'projects/t3code'), 'apps/web/src');
const css = await fs.readFile(path.join(t3, 'index.css'), 'utf8');
const blocks = [];
let open = false;
for (const line of css.split('\n')) {
  if (/^@(theme( inline)?|custom-variant \w+) /.test(line)) open = true;
  if (open) blocks.push(line);
  if (open && (line === '}' || /^@custom-variant .*;$/.test(line))) open = false;
}
// T3 marks dark mode with a class on <html>, which a selector inside a shadow root cannot see.
const theme = blocks.join('\n')
  .replace('(&:is(.dark, .dark *))', '(:host-context(.dark) &)')
  .replace('(&:not(.dark, .dark *))', '(:host-context(html:not(.dark)) &)')
  .replace('(&:is(.wco, .wco *))', '(:host-context(.wco) &)');
if (!theme.includes(':host-context(.dark)')) throw new Error("T3's dark variant is no longer `&:is(.dark, .dark *)`: update sync-t3.mjs");
await fs.writeFile('src/t3-theme.css', `/* Generated by sync-t3.mjs from T3 Code's index.css. Do not edit. */\n${theme}\n`);
for (const name of ['badge', 'kbd']) {
  const source = await fs.readFile(path.join(t3, 'components/ui', `${name}.tsx`), 'utf8');
  await fs.writeFile(`src/ui/${name}.tsx`, `// Copied by sync-t3.mjs from T3 Code (MIT). Do not edit.\n${source.replaceAll('~/lib/utils', '../cn')}`);
}
console.log(`Copied ${blocks.length} theme lines, badge.tsx and kbd.tsx from ${t3}`);
